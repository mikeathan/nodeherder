/**
 * Generate metrics data based on time range
 * Adjusts timestamps to fit within the requested period
 */
export function getMetricsForDevice(deviceId, expose, from, to) {
  const deviceData = mockMetricsData[deviceId];
  if (!deviceData) {
    return null;
  }

  const exposeData = deviceData[expose];
  if (!exposeData) {
    return null;
  }

  // Adjust timestamps to fit within the requested range
  const originalFrom = exposeData.type === 'binary' ? exposeData.data[0].timestamp : exposeData.data[0].x;
  const originalTo =
    exposeData.type === 'binary'
      ? exposeData.data[exposeData.data.length - 1].timestamp
      : exposeData.data[exposeData.data.length - 1].x;

  const originalRange = originalTo - originalFrom;
  const requestedRange = to - from;
  const scale = requestedRange / originalRange;

  let adjustedData;

  if (exposeData.type === 'binary') {
    // Adjust binary data timestamps
    adjustedData = exposeData.data.map((point) => ({
      timestamp: from + Math.floor((point.timestamp - originalFrom) * scale),
      value: point.value,
    }));
  } else {
    // Adjust numeric data timestamps
    adjustedData = exposeData.data.map((point) => ({
      x: from + Math.floor((point.x - originalFrom) * scale),
      y: point.y,
    }));
  }

  return {
    name: exposeData.name,
    type: exposeData.type,
    from: from,
    to: to,
    data: adjustedData,
  };
}

export function getAllMetricsForDevice(deviceId, from, to) {
  const deviceData = mockMetricsData[deviceId];
  if (!deviceData) {
    return [];
  }

  return Object.keys(deviceData)
    .map((expose) => getMetricsForDevice(deviceId, expose, from, to))
    .filter(Boolean);
}
