/*
 * Runtime contract for correlated device-settings saves over the existing
 * authenticated WebSocket. Replies contain metadata only, never configuration
 * or household positions.
 */

/** Correlated result metadata on the existing authenticated settings WebSocket. */
export type DeviceConfigSaveResult = { requestId: string; deviceId: string; success: boolean; error?: string };

/** Request opt-in preserves legacy clients; the reply never contains configuration or positions. */
export const DEVICE_CONFIG_SAVE_RESULT = 'deviceConfigSaveResult';
/** Canonical UUID correlation token generated by the browser. */
export const DEVICE_SETTINGS_REQUEST_ID_PATTERN = /^[\da-f]{8}-[\da-f]{4}-[\da-f]{4}-[\da-f]{4}-[\da-f]{12}$/i;
/** Maximum bytes for a device identifier echoed in a result. */
export const MAX_DEVICE_SETTINGS_ID_LENGTH = 256;
/** Maximum bytes for bounded recovery text in a result. */
export const MAX_DEVICE_SETTINGS_ERROR_LENGTH = 512;

/** Validates untrusted reply metadata before it can confirm a pending save; invalid or contradictory replies return null. */
export function parseDeviceConfigSaveResult(value: unknown): DeviceConfigSaveResult | null {
  if (!value || typeof value !== 'object') return null;
  const result = value as Record<string, unknown>;
  if (
    typeof result.requestId !== 'string' ||
    !DEVICE_SETTINGS_REQUEST_ID_PATTERN.test(result.requestId) ||
    typeof result.deviceId !== 'string' ||
    !result.deviceId ||
    result.deviceId.length > MAX_DEVICE_SETTINGS_ID_LENGTH ||
    result.deviceId.includes('\0') ||
    typeof result.success !== 'boolean'
  ) {
    return null;
  }
  if (
    result.error !== undefined &&
    (typeof result.error !== 'string' || result.error.length > MAX_DEVICE_SETTINGS_ERROR_LENGTH)
  ) {
    return null;
  }
  if (result.success && result.error) return null;
  return {
    requestId: result.requestId,
    deviceId: result.deviceId,
    success: result.success,
    ...(typeof result.error === 'string' ? { error: result.error } : {}),
  };
}
